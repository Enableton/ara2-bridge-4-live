#!/usr/bin/env python3
"""Build device/build/bridge.js for Max's classic js object.

Max's js has no module loader, so the device's js object loads ONE file: src/core.js followed by src/bridge.js.
core.js ends with its UMD footer (`module.exports = core` under node, the global ARACore in Max); bridge.js uses
ARACore and falls back to core.js's top-level `core` variable when the built file is loaded with a `module` object.

    python3 device/build.py          # writes device/build/bridge.js, then checks it

Checks on the generated file (exit code 1 on any failure):
  - ES5 scan (the same patterns as device/tests/test_core.js): no let/const/arrow functions/template literals/classes/
    spread/Object.assign/.includes(/.find(/.findIndex(/startsWith/endsWith/padStart/repeat(/for...of/...;
  - no file-level 'use strict' before core.js's IIFE (Max's js would apply it to everything that follows);
  - `node --check` (when node is on PATH).

device/build/ is git-ignored (generated). The .amxd refers to device/build/bridge.js by absolute path, so
device/make_amxd.py runs this script first.
"""
import os
import re
import shutil
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SOURCES = [os.path.join(HERE, "src", "core.js"), os.path.join(HERE, "src", "bridge.js")]
OUT_DIR = os.path.join(HERE, "build")
OUT = os.path.join(OUT_DIR, "bridge.js")

# Removes comments and string literals in one pass so the scan sees code only (port of test_core.js codeOnly).
CODE_ONLY_RE = re.compile(r"//[^\n]*|/\*[\s\S]*?\*/|'(?:[^'\\\n]|\\.)*'|\"(?:[^\"\\\n]|\\.)*\"")

ES6_PATTERNS = [
    (r"\blet\b", "let"), (r"\bconst\b", "const"), (r"=>", "arrow function"), (r"`", "template literal"),
    (r"\bclass\b", "class"), (r"\.\.\.", "spread/rest"), (r"\bObject\.assign\b", "Object.assign"),
    (r"\.includes\s*\(", ".includes("), (r"\bpadStart\b|\bpadEnd\b", "padStart/padEnd"),
    (r"\.startsWith\s*\(|\.endsWith\s*\(", "startsWith/endsWith"),
    (r"\bNumber\.(isFinite|isInteger|isNaN|isSafeInteger|EPSILON)\b", "Number.is*"),
    (r"\bArray\.from\b|\bArray\.of\b", "Array.from/of"), (r"\.find\s*\(|\.findIndex\s*\(", "find/findIndex"),
    (r"\.repeat\s*\(", "repeat"), (r"\bObject\.(values|entries)\b", "Object.values/entries"),
    (r"\bMath\.(trunc|sign|log2|log10|hypot|cbrt)\b", "Math.* (ES6)"), (r"\bnew\s+(Map|Set|WeakMap|WeakSet)\b", "Map/Set"),
    (r"\bPromise\b", "Promise"), (r"\bSymbol\b", "Symbol"), (r"\basync\b|\bawait\b|\byield\b", "async/await/yield"),
    (r"function\s*\*", "generator"), (r"\*\*", "** operator"), (r"\?\.", "optional chaining"), (r"\?\?", "nullish coalescing"),
    (r"\bfor\s*\([^)]*\sof\s", "for...of"), (r"\bimport\s|\bexport\s", "import/export"), (r"\.at\s*\(", ".at("),
    (r"\bString\.raw\b|\.normalize\s*\(|\.codePointAt\s*\(|\bfromCodePoint\b", "ES6 string methods"),
    (r"\binclude\s*\(", "include( (Max js include: the build concatenates instead)"),
]


def code_only(src):
    return CODE_ONLY_RE.sub(" ", src)


def es5_violations(src):
    code = code_only(src)
    out = []
    for pattern, name in ES6_PATTERNS:
        m = re.search(pattern, code)
        if m:
            line = code.count("\n", 0, m.start()) + 1
            out.append("%s (line %d)" % (name, line))
    return out


_TMP_SEQ = 0


def build():
    parts = ["// GENERATED by device/build.py from src/core.js + src/bridge.js. Do not edit; edit the sources.\n"]
    for p in SOURCES:
        with open(p, "r", encoding="utf-8") as f:
            text = f.read()
        if not text.endswith("\n"):
            text += "\n"
        parts.append("\n// ======================================================================== %s\n" % os.path.relpath(p, HERE))
        parts.append(text)
    out = "".join(parts)
    os.makedirs(OUT_DIR, exist_ok=True)
    # unique temp name in the same folder: two parallel builds never write the same temp file
    global _TMP_SEQ
    _TMP_SEQ += 1
    tmp = "%s.%d-%d.tmp" % (OUT, os.getpid(), _TMP_SEQ)
    with open(tmp, "w", encoding="utf-8") as f:
        f.write(out)
    os.replace(tmp, OUT)
    return out


def check(out):
    problems = ["ES5: " + v for v in es5_violations(out)]
    head = out.split("var core = (function")[0]
    if re.search(r"^\s*['\"]use strict['\"]", re.sub(r"//[^\n]*", "", head), re.M):
        problems.append("file-level 'use strict' before core.js")
    node = shutil.which("node")
    if node:
        r = subprocess.run([node, "--check", OUT], capture_output=True, text=True)
        if r.returncode != 0:
            problems.append("node --check failed: " + (r.stderr or r.stdout).strip())
    else:
        print("build.py: node not on PATH, skipped node --check", file=sys.stderr)
    return problems


def main():
    out = build()
    problems = check(out)
    if problems:
        for p in problems:
            print("build.py: " + p, file=sys.stderr)
        print("build.py: FAILED (%s)" % OUT, file=sys.stderr)
        return 1
    print("build.py: wrote %s (%d bytes), ES5 scan and node --check passed" % (OUT, len(out.encode("utf-8"))))
    return 0


if __name__ == "__main__":
    sys.exit(main())
